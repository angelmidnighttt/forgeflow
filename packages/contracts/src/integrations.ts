import { z } from 'zod';

/**
 * The kinds of outside systems an organization connects, by the phase that adds them:
 * GitHub (2); Alertmanager and generic webhooks (3); Prometheus, Loki, Tempo (4).
 */
export const INTEGRATION_KINDS = [
  'github',
  'alertmanager',
  'webhook',
  'prometheus',
  'loki',
  'tempo',
] as const;
export type IntegrationKind = (typeof INTEGRATION_KINDS)[number];

/** A secret's name within its integration: `signing_secret`, `password`… */
export const SECRET_NAME_PATTERN = /^[a-z][a-z0-9_]{0,62}$/;
export const SECRET_VALUE_MAX_LENGTH = 4096;

/**
 * What the API tells about an integration's secret: never its value, only which version is in
 * use and whether it still is. `source`: generated by ForgeFlow, or provided by the user.
 */
export const integrationSecretSchema = z.object({
  name: z.string(),
  version: z.number().int().min(1),
  source: z.enum(['generated', 'provided']),
  status: z.enum(['active', 'revoked']),
  /** When the current version was created, or revoked. */
  updatedAt: z.iso.datetime(),
});
export type IntegrationSecret = z.infer<typeof integrationSecretSchema>;

export const integrationSchema = z.object({
  id: z.uuid(),
  /** One of INTEGRATION_KINDS (text, so that a newer kind still parses). */
  kind: z.string(),
  name: z.string(),
  status: z.enum(['active', 'disabled']),
  /** Null for an integration of the whole organization. */
  projectId: z.uuid().nullable(),
  /** Settings that are not secret (URLs, ids). */
  config: z.record(z.string(), z.unknown()),
  externalId: z.string().nullable(),
  secrets: z.array(integrationSecretSchema),
  createdAt: z.iso.datetime(),
});
export type Integration = z.infer<typeof integrationSchema>;

/**
 * POST /api/v1/organizations/:orgId/integrations/:integrationId/secrets/:name/rotate
 * A provided secret needs its new `value`; ForgeFlow makes up a generated one (send no value,
 * or no body at all).
 */
export const rotateIntegrationSecretRequestSchema = z
  .object({ value: z.string().min(1).max(SECRET_VALUE_MAX_LENGTH).optional() })
  .default({});
export type RotateIntegrationSecretRequest = z.infer<typeof rotateIntegrationSecretRequestSchema>;

/**
 * The new version. `value` is the new value of a generated secret, shown this once (to paste
 * into the other system); null for a provided one.
 */
export const rotatedIntegrationSecretSchema = z.object({
  secret: integrationSecretSchema,
  value: z.string().nullable(),
});
export type RotatedIntegrationSecret = z.infer<typeof rotatedIntegrationSecretSchema>;
